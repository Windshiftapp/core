#!/usr/bin/env node

import { readdir, writeFile } from 'node:fs/promises';

const locales = (
  await readdir(new URL('../frontend/src/lib/locales/', import.meta.url), { withFileTypes: true })
)
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const keyMappings = {
  priority: {
    critical: 'critical',
    high: 'high',
    medium: 'medium',
    low: 'low',
  },
  status_category: {
    toDo: 'to_do',
    inProgress: 'in_progress',
    done: 'done',
  },
  status: {
    open: 'open',
    inProgress: 'in_progress',
    done: 'done',
  },
  item_type: {
    initiative: 'initiative',
    epic: 'epic',
    story: 'story',
    task: 'task',
    bug: 'bug',
    subtask: 'subtask',
  },
  hierarchy_level: {
    initiative: 'initiative',
    epic: 'epic',
    story: 'story',
    task: 'task',
    activity: 'activity',
  },
  link_type: {
    tests: 'tests',
    implements: 'implements',
    dependsOn: 'depends_on',
    relatesTo: 'relates_to',
    linksTo: 'links_to',
    duplicates: 'duplicates',
    childOf: 'child_of',
    page: 'page',
  },
  workspace_role: {
    viewer: 'viewer',
    editor: 'editor',
    tester: 'tester',
    administrator: 'administrator',
  },
  theme: {
    default: 'default',
    ocean: 'ocean',
    forest: 'forest',
  },
};

function addFields(rows, objectType, builtinKey, locale, value) {
  if (typeof value === 'string') {
    rows.push({ objectType, builtinKey, field: 'name', locale, value });
    return;
  }
  for (const field of ['name', 'description']) {
    if (typeof value?.[field] === 'string' && value[field].trim()) {
      rows.push({ objectType, builtinKey, field, locale, value: value[field] });
    }
  }
}

function addMapped(rows, objectType, locale, values) {
  for (const [localeKey, builtinKey] of Object.entries(keyMappings[objectType])) {
    addFields(rows, objectType, builtinKey, locale, values?.[localeKey]);
  }
}

const rows = [];
for (const locale of locales) {
  const merged = (await import(`../frontend/src/lib/locales/${locale}/index.js`)).default;
  const workflows = (await import(`../frontend/src/lib/locales/${locale}/workflows.js`)).default;

  addMapped(rows, 'priority', locale, merged.priorities);
  addMapped(rows, 'status_category', locale, merged.settings.statusCategories.defaults);
  addMapped(rows, 'status', locale, merged.statuses.defaults);
  addMapped(rows, 'item_type', locale, merged.settings.itemTypes.defaults);
  addMapped(rows, 'hierarchy_level', locale, merged.settings.hierarchyLevels.defaults);
  addMapped(rows, 'link_type', locale, merged.settings.linkTypes.defaults);
  addMapped(rows, 'workspace_role', locale, merged.workspaceMembers.roles);
  addMapped(rows, 'theme', locale, merged.settings.themeManager.defaults);

  addFields(
    rows,
    'configuration_set',
    'default',
    locale,
    merged.settings.configSets.defaults.configuration
  );
  addFields(
    rows,
    'notification_setting',
    'default',
    locale,
    merged.settings.configSets.defaults.notifications
  );
  addFields(rows, 'workflow', 'default', locale, merged.workflows.defaults.default);
  addFields(rows, 'screen', 'default', locale, workflows.screensPage.defaults.default);
  addFields(
    rows,
    'screen',
    'default_create',
    locale,
    workflows.screensPage.defaults.default_create
  );
}

const quote = (value) =>
  JSON.stringify(value).replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
const body = rows
  .map(
    (row) =>
      `\t{ObjectType: ${quote(row.objectType)}, BuiltinKey: ${quote(row.builtinKey)}, Field: ${quote(row.field)}, Locale: ${quote(row.locale)}, Value: ${quote(row.value)}},`
  )
  .join('\n');

const generated = `// Code generated by scripts/generate-object-translation-catalog.mjs; DO NOT EDIT.\n\npackage objecttranslation\n\nvar shippedSystemTranslations = []SystemTranslation{\n${body}\n}\n`;

await writeFile(
  new URL('../internal/objecttranslation/system_catalog_generated.go', import.meta.url),
  generated
);
