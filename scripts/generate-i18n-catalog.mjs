#!/usr/bin/env bun

/**
 * Generates internal/i18n/date_formats_generated.go and
 * internal/i18n/catalog_generated.go from the canonical frontend locale data.
 *
 * - Date layouts come from frontend/src/lib/locales/dateFormats.js.
 * - Email copy comes from frontend/src/lib/locales/<locale>/email.js.
 *
 * Keeping both next to the locale catalogs means the i18n guard
 * (frontend/scripts/check-i18n.js) covers them, and the backend gets the same
 * values with no hand copy.
 *
 * Usage:
 *   bun scripts/generate-i18n-catalog.mjs           # write the Go files
 *   node scripts/generate-i18n-catalog.mjs --check   # fail if they are stale
 */

import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');

const { DATE_FORMATS } = await import(
  new URL('../frontend/src/lib/locales/dateFormats.js', import.meta.url)
);

const quote = (value) => JSON.stringify(value);

// Format generated Go with the project's gofmt so `gofmt -l` stays clean and
// --check compares against the exact bytes that would be written.
const gofmt = (source) => execFileSync('gofmt', [], { input: source, encoding: 'utf-8' });

// --- Date formats ---

const dateTarget = join(repoRoot, 'internal/i18n/date_formats_generated.go');
const dateLocales = Object.keys(DATE_FORMATS).sort();
const dateBody = dateLocales
  .map((locale) => {
    const { date, dateTime, time } = DATE_FORMATS[locale];
    return `\t${quote(locale)}: {Date: ${quote(date)}, DateTime: ${quote(dateTime)}, Time: ${quote(time)}},`;
  })
  .join('\n');

const dateGenerated = gofmt(`// Code generated by scripts/generate-i18n-catalog.mjs; DO NOT EDIT.

package i18n

// dateFormats holds the numeric date/time layout for each shipped locale.
// Source: frontend/src/lib/locales/dateFormats.js
var dateFormats = map[string]dateFormat{
${dateBody}
}
`);

// --- Email catalog ---

function flatten(value, prefix, out) {
  if (typeof value === 'string') {
    out.push([prefix, value]);
    return;
  }
  if (value === null || typeof value !== 'object') return;
  for (const key of Object.keys(value).sort()) {
    flatten(value[key], prefix ? `${prefix}.${key}` : key, out);
  }
}

const catalogTarget = join(repoRoot, 'internal/i18n/catalog_generated.go');
const catalogBody = [];
for (const locale of dateLocales) {
  const mod = await import(
    new URL(`../frontend/src/lib/locales/${locale}/email.js`, import.meta.url)
  );
  const entries = [];
  flatten(mod.default ?? mod, '', entries);
  const lines = entries
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `\t\t${quote(key)}: ${quote(value)},`)
    .join('\n');
  catalogBody.push(`\t${quote(locale)}: {\n${lines}\n\t},`);
}

const catalogGenerated = gofmt(`// Code generated by scripts/generate-i18n-catalog.mjs; DO NOT EDIT.

package i18n

// catalog holds backend-rendered copy (currently email) for each shipped
// locale. Source: frontend/src/lib/locales/<locale>/email.js
var catalog = map[string]map[string]string{
${catalogBody.join('\n')}
}
`);

// --- Write or check ---

const targets = [
  [dateTarget, dateGenerated],
  [catalogTarget, catalogGenerated],
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [target, generated] of targets) {
    const existing = await readFile(target, 'utf-8').catch(() => '');
    if (existing !== generated) {
      console.error(
        `${target.slice(repoRoot.length + 1)} is out of date; run \`bun scripts/generate-i18n-catalog.mjs\``
      );
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('i18n date formats and catalog are up to date');
} else {
  for (const [target, generated] of targets) {
    await writeFile(target, generated);
  }
}
